"""
LangGraph state schema for the KodeBuddy AI learning assistant agent.

This defines the single shared state object that flows through the graph:
retrieve -> (reason -> confidence_gate) | no_context -> route.

Owner: Dev C (Graph / Reasoning / Guardrails)
"""

from __future__ import annotations

from enum import Enum
from typing import TypedDict


class QueryType(str, Enum):
    """Distinguishes a general curriculum question from assignment guidance."""

    CHAT = "chat"
    ASSIGNMENT_GUIDANCE = "assignment_guidance"


class EscalationReason(str, Enum):
    """
    Structured escalation categories, replacing free-form strings so Dev E's
    tracing tools and Dev D's analytics endpoints can aggregate escalation
    metrics by category instead of parsing prose.

    `AgentState.escalation_detail` carries any free-form context (e.g. the
    actual top retrieval score) alongside the category, so nothing is lost
    versus the old free-text approach — it's just structured now.
    """

    NO_RELEVANT_CONTEXT = "no_relevant_context"
    LOW_RETRIEVAL_CONFIDENCE = "low_retrieval_confidence"
    MODEL_UNCERTAINTY = "model_uncertainty"
    POLICY_VIOLATION = "policy_violation"
    PARSER_FAILURE = "parser_failure"
    # Reserved for a future "talk to a human" intent-detection feature.
    # Not yet triggered anywhere in this graph.
    EXPLICIT_USER_REQUEST = "explicit_user_request"


class RetrievedChunk(TypedDict):
    """One retrieved piece of grounding content, as returned by Dev B's tools.

    Entity ids are `int` to match the backend's primary keys (users, courses,
    modules are all int PKs). `chunk_id` stays `str`: it's generated by Dev
    A's ingestion pipeline, not a backend row id.
    """

    chunk_id: str
    course_id: int
    module_id: int | None
    content_type: str  # "curriculum" | "faq" | "resource"
    text: str
    score: float


class ChatTurn(TypedDict):
    """One turn of prior conversation, as loaded from conversation_history.

    This is the *agreed* shape. In practice, treat it as best-effort: use
    the accessors in graph/utils.py (chat_turn_role/chat_turn_message)
    rather than direct key access, so a turn from a slightly different
    source (e.g. a LangChain-style message object) degrades gracefully
    instead of raising a KeyError.
    """

    role: str  # "user" | "assistant"
    message: str


class AssignmentBrief(TypedDict):
    """
    Structured assignment data from Dev B's get_assignment_brief tool.

    Deliberately structured rather than a pre-formatted string: how
    due_date/maximum_score get phrased into the prompt is a prompt-design
    decision, and prompts/assignment_guidance.py (owned by Dev C) is where
    that decision should live.

    due_date is an ISO 8601 date string (e.g. "2026-09-01") rather than a
    datetime object, so this TypedDict has no datetime-library dependency
    and serializes cleanly if it ever needs to cross a process boundary.
    """

    assignment_id: int
    course_id: int
    module_id: int
    title: str
    description: str
    due_date: str | None
    maximum_score: int | None


class AgentState(TypedDict, total=False):
    """
    Shared state object passed between graph nodes.

    Fields are grouped by which node reads/writes them:
      - input fields:      set once by Dev D's service.py before graph.invoke()
      - retrieve fields:   written by `retrieve`, read by `reason`/`no_context`
      - reason fields:
        written by `reason` (or `no_context`), read by `confidence_gate`
      - gate fields:
        written by `confidence_gate` (or `no_context`), read by `route`
      - output fields:   written by `route`, read by Dev D's service.py

    IMPORTANT — state is per-turn, not accumulating: every graph.invoke()
    call should receive a state containing only the input fields below. The
    `retrieve` node explicitly strips any other keys at the top of its run
    (see nodes.py::_reset_transient_fields) specifically so that reusing or
    mutating a state dict across turns can't leak a previous turn's
    escalation_reason, is_confident, etc. into the current one.
    """

    # --- input (set by Dev D's service.py before invoking the graph) ---
    learner_id: int
    course_id: int
    module_id: int | None
    assignment_id: int | None
    # The user assigned as trainer for this learner's course/cohort.
    # The backend has no separate `trainers` table/module - trainers,
    # learners, mentors, and admins are all rows in one `users` table,
    # distinguished by a role field. So this is a `users.id` value, not a
    # dedicated "trainer" primary key — resolved upstream (Dev D, from
    # whatever course/cohort -> assigned-trainer-user lookup the backend
    # exposes) and passed straight through here. Optional because
    # escalation must still work (rather than silently drop the question)
    # if that lookup failed; None just means Dev B's escalate_to_trainer
    # needs a fallback target.
    trainer_id: int | None
    question: str
    query_type: QueryType
    # windowed recent history, loaded by Dev E's history logic
    chat_history: list[ChatTurn]

    # --- retrieve node output ---
    retrieved_chunks: list[RetrievedChunk]
    # only populated for ASSIGNMENT_GUIDANCE
    assignment_brief: AssignmentBrief | None

    # --- reason node output (also set directly by `no_context`) ---
    draft_response: str
    model_expressed_uncertainty: bool
    # True if the drafted response appears to violate "guide, don't solve"
    # (see nodes.py::_violates_guide_dont_solve_policy). Only ever computed
    # for ASSIGNMENT_GUIDANCE; always False for CHAT.
    policy_violation: bool
    # True if the model's response couldn't be parsed as the expected
    # {"answer": ..., "uncertain": ...} JSON shape. Kept distinct from
    # model_expressed_uncertainty so a formatting failure and a genuine
    # "the model wasn't sure" are distinguishable in telemetry.
    parser_failed: bool

    # --- confidence_gate node output (also set directly by `no_context`) ---
    confidence_score: float
    is_confident: bool
    escalation_reason: EscalationReason | None
    escalation_detail: str | None

    # --- route node output (final) ---
    final_response: str | None
    escalated: bool
    escalation_id: int | None
